export function translator(locale: string) {
  const dict = locale.toLowerCase().startsWith("zh") ? zh : en;
  return (key: Key, vars: Record<string, string> = {}) =>
    dict[key].replace(/\{(\w+)\}/g, (_, k: string) => vars[k] ?? "");
}
